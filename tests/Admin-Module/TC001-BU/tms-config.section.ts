import { Page } from "@playwright/test";
import { tryAction, safeClick } from "../../../helpers";

/**
 * Helper เลือก Dropdown โดยตรง
 */
async function selectOptionDirect(page: Page, selector: string, value?: string) {
  if (!value) return;

  return await tryAction(async () => {
    const dropdown = page.locator(selector).first();
    await dropdown.waitFor({ state: "attached", timeout: 3000 });

    await dropdown.selectOption({ label: value }).catch(async () => {
      await dropdown.selectOption({ value: value }).catch(() => {});
    });
    await dropdown.dispatchEvent("change").catch(() => {});
  }, `Select "${value}" in "${selector}"`);
}

export class TMSConfigSection {
  constructor(private page: Page) {}

  /** 1. ตั้งค่าหมวด Delivery Order */
  async configureDeliveryOrder(data: any): Promise<void> {
    await tryAction(async () => {
      // Delivery Note Report Name
      const reportName = data.deliveryNoteReportFormatName || data.deliveryNoteReportName;
      if (reportName) {
        const reportInput = this.page.locator("#txtDeliveryNoteReportName").first();
        if (await reportInput.isVisible({ timeout: 2000 }).catch(() => false)) {
          await reportInput.fill(reportName);
          await reportInput.dispatchEvent("input").catch(() => {});
          await reportInput.dispatchEvent("change").catch(() => {});
        }
      }

      // Collect Transportation Charge
      const payer = data.transportChargePayer || data.transportCharge;
      if (payer) {
        await selectOptionDirect(this.page, "select#ddTransportCharge", payer);
      }

      // Checkbox: Auto-Generate Delivery Order (อ้างอิงจาก Param ใน HTML)
      const isAutoDO = data.isAutoGenerateDeliveryOrder ?? data.autoGenerateDeliveryOrder;
      if (isAutoDO) {
        const cb = this.page.locator("gisc-ui-checkbox[params*='BU_TMSAutoGenerateDeliveryOrder']").first();
        await cb.locator("label, .app-control-indicator").first().click({ force: true }).catch(() => {});
      }

      if (isAutoDO) {
        // Format
        if (data.deliveryOrderFormat) {
          const formatInput = this.page.locator("#deliveryOrderFormat").first();
          await formatInput.waitFor({ state: "visible", timeout: 3000 });
          await formatInput.fill(data.deliveryOrderFormat);
          await formatInput.dispatchEvent("input").catch(() => {});
          await formatInput.dispatchEvent("change").catch(() => {});
        }
        
        // Reset Type (id: ddResetType_do)
        if (data.deliveryOrderResetCycle) {
          await selectOptionDirect(this.page, "select#ddResetType_do", data.deliveryOrderResetCycle);
        }

        // Format Date / Running Date (id: ddDeliveryRunningDate)
        if (data.deliveryOrderDateSource) {
          await selectOptionDirect(this.page, "select#ddDeliveryRunningDate", data.deliveryOrderDateSource);
        }

        // Checkbox: Year is B.E. ของ Delivery Order
        const isYearBE = data.isDeliveryOrderYearBuddhistEra ?? data.doYearIsBE;
        if (isYearBE) {
          const doFieldset = this.page.locator("fieldset").filter({ hasText: "Delivery Order" }).first();
          await doFieldset.locator("gisc-ui-checkbox").filter({ hasText: "Year is B.E." }).locator("label, .app-control-indicator").first().click({ force: true }).catch(() => {});
        }
      }
    }, "Configure Delivery Order");
  }

/** 2. ตั้งค่าหมวด Job */
  async configureJob(data: any): Promise<void> {
    await tryAction(async () => {
      // 📌 แก้ไขให้ค้นหา Fieldset จากคำที่มีอยู่ข้างในจริงๆ
      const jobFieldset = this.page.locator("fieldset").filter({ hasText: "Auto-Generate Shipment Code" }).first();
      await jobFieldset.scrollIntoViewIfNeeded().catch(() => {});
      await this.page.waitForTimeout(300);

      // Checkbox: Auto-Generate Shipment Code
      const isAutoJob = data.isAutoGenerateShipmentCode ?? data.autoGenerateJobOrder;
      if (isAutoJob) {
        // 📌 กลับมาใช้ Label Filter ที่เสถียรที่สุดสำหรับ Checkbox ตัวนี้
        const autoCb = jobFieldset.locator("label").filter({ hasText: "Auto-Generate Shipment Code" }).first();
        await autoCb.click({ force: true }).catch(() => {});
      }

      if (isAutoJob) {
        // Job Format (id: jobFormat)
        if (data.jobOrderFormat || data.jobFormat) {
          const formatInput = this.page.locator("#jobFormat").first();
          await formatInput.waitFor({ state: "visible", timeout: 3000 });
          await formatInput.fill(data.jobOrderFormat || data.jobFormat);
          await formatInput.dispatchEvent("input").catch(() => {});
          await formatInput.dispatchEvent("change").catch(() => {});
        }

        // Reset Type (id: ddResetType_job)
        if (data.jobOrderResetCycle || data.jobResetCycle) {
          await selectOptionDirect(this.page, "select#ddResetType_job", data.jobOrderResetCycle || data.jobResetCycle);
        }

        // Apply to Shipment Name
        const isApplyName = data.isApplyToShipmentName ?? data.applyToShipmentName;
        if (isApplyName) {
          const applyCb = jobFieldset.locator("label").filter({ hasText: "Apply to Shipment Name" }).first();
          await applyCb.click({ force: true }).catch(() => {});
        }

        // Format Name (id: jobNameFormat)
        if (!isApplyName && (data.jobNameFormat || data.shipmentNameFormat)) {
          const jobNameInput = this.page.locator("#jobNameFormat").first();
          if (await jobNameInput.isVisible({ timeout: 2000 }).catch(() => false)) {
            await jobNameInput.fill(data.jobNameFormat || data.shipmentNameFormat);
            await jobNameInput.dispatchEvent("input").catch(() => {});
            await jobNameInput.dispatchEvent("change").catch(() => {});
          }
        }

        // Checkbox: Year is B.E. ของ Job
        const isJobYearBE = data.isJobOrderYearBuddhistEra ?? data.jobYearIsBE;
        if (isJobYearBE) {
          await jobFieldset.locator("gisc-ui-checkbox").filter({ hasText: "Year is B.E." }).locator("label, .app-control-indicator").first().click({ force: true }).catch(() => {});
        }
      }
    }, "Configure Job");
  }

  /** 3. ตั้งค่าหมวด Receipt */
  async configureReceipt(data: any): Promise<void> {
    await tryAction(async () => {
      const receiptFieldset = this.page.locator("fieldset").filter({ hasText: "Receipt" }).first();
      await receiptFieldset.scrollIntoViewIfNeeded().catch(() => {});
      await this.page.waitForTimeout(300);

      // Format (id: txtReceiptFormat)
      if (data.receiptFormat) {
        const formatInput = this.page.locator("#txtReceiptFormat").first();
        await formatInput.waitFor({ state: "visible", timeout: 3000 });
        await formatInput.fill(data.receiptFormat);
        await formatInput.dispatchEvent("input").catch(() => {});
        await formatInput.dispatchEvent("change").catch(() => {});
      }

      // Reset Type (id: ddReceiptResetType)
      if (data.receiptResetCycle) {
        await selectOptionDirect(this.page, "select#ddReceiptResetType", data.receiptResetCycle);
      }

      // Checkbox: Year is B.E. ของ Receipt
      const isReceiptYearBE = data.isReceiptYearBuddhistEra ?? data.receiptYearIsBE;
      if (isReceiptYearBE) {
        await receiptFieldset.locator("gisc-ui-checkbox").filter({ hasText: "Year is B.E." }).locator("label, .app-control-indicator").first().click({ force: true }).catch(() => {});
      }
    }, "Configure Receipt");
  }

  /** กดปุ่ม OK บันทึก */
  async submitConfig(): Promise<void> {
    await tryAction(async () => {
      const okButton = this.page.getByRole('button', { name: 'OK' }).first();
      await okButton.waitFor({ state: "visible", timeout: 3000 });
      await okButton.click({ force: true });
    }, "Submit TMS");
  }
}