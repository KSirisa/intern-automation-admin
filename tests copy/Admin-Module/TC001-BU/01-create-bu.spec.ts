test("business unit test - robust & dynamic field order", async ({ page }) => {
  test.setTimeout(180000);

  await test.step("1. Navigate to Business Unit Hierarchy", async () => {
    await page.goto("/admin#/business-unit-menu");

    const hierarchyLink = page.getByRole("link", { name: "Business Unit Hierarchy", exact: true });
    await hierarchyLink.waitFor({ state: "visible", timeout: 5000 });
    await safeClick(hierarchyLink, "Hierarchy Link");

    const createBtn = page.getByTitle("Create", { exact: true });
    await safeClick(createBtn, "Create Button");
  });

  await test.step("2. Fill General Info", async () => {
    await page.locator("#txtName").fill(testData.businessUnitName);
    await page.getByRole("textbox", { name: "Code", exact: true }).fill(testData.businessUnitCode);
    await page.locator("#txtDescription").fill(testData.businessUnitDescription);

    await selectBUTreeviewNode(
      page,
      testData.parentBusinessUnitName,
      'gisc-ui-dropdowntree[params*="parentOptions"], gisc-ui-dropdowntree'
    );
    await selectByLabel(page, "ddlBusinessEntityType", testData.businessEntityType);
    await selectByLabel(page, "managerOptions", testData.vehicleManagerUsername);
    await selectByLabel(page, "maintenanceManager", testData.maintenanceManagerUsername);
  }); 

  await test.step("3. Add Authorized Persons", async () => {
    await addAuthorizedUsersModal(page, testData.initialAuthorizedUsers);
    await addAuthorizedUsersModal(page, testData.reAddedAuthorizedUsers);
  }); 

  await test.step("4. Configure 'Apply To' Target & Options", async () => {
    // 📌 ทำงานตามสวิตช์โหมดใน testData ด้านบนสุดโดยอัตโนมัติ
    await configureApplyTo(page, testData);
  });

  await test.step("5. Configure TMS Settings", async () => {
    await safeClick(page.getByRole("link", { name: "TMS Configurations" }), "TMS Configurations SubMenu");
    const tms = new TMSConfigSection(page);
    await tms.configureDeliveryOrder(testData);
    await tms.configureJob(testData);
    await tms.configureReceipt(testData);
    await tms.submitConfig();
  });

  await test.step("6. Configure POD Settings", async () => {
    await safeClick(page.getByRole("link", { name: "POD Configurations" }), "POD Configurations SubMenu");
    const podSection = new PODConfigSection(page);

    await podSection.configurePOD(testData);
    await podSection.submitConfig();
  });

  await test.step("7. Configure Maintenance Management Settings", async () => {
    await safeClick(page.getByRole("link", { name: "Maintenance Management Configuration" }), "Maintenance Management Configuration SubMenu");
    const maintenanceSection = new MaintenanceConfigSection(page);

    await maintenanceSection.configureMaintenance(testData);
    await maintenanceSection.submitConfig();
  });

  await test.step("8. Configure Shipment Settings", async () => {
    await safeClick(page.getByRole("link", { name: "Shipment Configuration" }), "Shipment Configuration SubMenu");
    const shipmentSection = new ShipmentConfigSection(page);

    await shipmentSection.configureShipment(testData);
    await shipmentSection.submitConfig();
  });

  await test.step("9. Configure System Settings", async () => {
    await safeClick(page.getByRole("link", { name: "System Configuration" }), "System Configuration SubMenu");
    const systemSection = new SystemConfigSection(page);

    await systemSection.configureSystem(testData);
    await systemSection.submitConfig();
  });

  // await test.step("10. Save Main Form & Assert BU Creation", async () => {
  //   await saveAndVerifyMainBUForm(page, testData.businessUnitName);
  // });

  await page.pause();
});